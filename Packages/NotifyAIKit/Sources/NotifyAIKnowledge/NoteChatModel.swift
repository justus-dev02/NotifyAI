/// A passage an answer is based on, shown as a tappable source card.
public struct ChatSource: Identifiable, Hashable, Sendable {
    public let number: Int
    public let noteID: UUID
    public let noteTitle: String
    public let noteDate: Date
    let labels: [String]
    let noteKind: NoteKind
    public let start: TimeInterval?
    public let excerpt: String
    public let isSummary: Bool
    public var id: Int { number }
}

/// A note that matches the question.
public struct ChatNoteLink: Identifiable, Hashable, Sendable {
    public let noteID: UUID
    public let title: String
    public let date: Date
    public let kind: NoteKind
    public let reasons: [String]
    public var id: UUID { noteID }
}

public struct ChatMessage: Identifiable, Sendable {
    public enum Role: Sendable {
        case user
        case assistant
    }

    public let id = UUID()
    public let role: Role
    public var text: String
    public var sources: [ChatSource] = []
    public var notes: [ChatNoteLink] = []
    /// The filters the question was understood with ("Letzte Woche", "Person: Anna").
    public var filters: [String] = []
    /// Additional information, e.g. that the answer was not generated by the language model.
    public var notice: String?
    /// The notes a summary across several notes can be made from, when the question asked
    /// for one ("Fasse alle Samsung-Meetings zusammen").
    public var collectionNoteIDs: [UUID] = []
    public var isPending = false
    /// While pending: the current step of a longer answer ("Lese Notiz 2 von 5 …").
    public var status: String?
}

/// "Notizen fragen": the conversation about all notes – its messages, sending, cancelling.
/// `NoteQuestionAnswering` answers each question.
///
/// Pipeline for every question:
/// 1. **Understand** – rules (dates, known names, kinds) plus, with Apple Intelligence, a
///    structured search plan (rewritten query, synonyms, people, time frame, follow-ups).
/// 2. **Retrieve** – hybrid full-text and semantic search with the filters applied.
/// 3. **Answer** – the language model answers from the best passages only and cites them.
///    A question spread over several notes ("Was wurde bisher entschieden?") is answered from
///    every matching note instead (`CrossNoteAnswering`). Without Apple Intelligence the best
///    passages are shown directly.
@MainActor
@Observable
public final class NoteChatModel {
    public private(set) var messages: [ChatMessage] = []
    public private(set) var isResponding = false

    @ObservationIgnored private let answering: NoteQuestionAnswering
    @ObservationIgnored private let now: @Sendable () -> Date
    @ObservationIgnored private var responseTask: Task<Void, Never>?

    public static let suggestions = [
        String(localized: "Welche Aufgaben habe ich diese Woche übernommen?", bundle: .module),
        String(localized: "Was wurde zuletzt entschieden?", bundle: .module),
        String(localized: "Welche Fragen sind noch offen?", bundle: .module),
        String(localized: "Zeig mir alle Aufnahmen von letzter Woche", bundle: .module),
    ]

    package init(
        knowledge: KnowledgeIndexService,
        settings: AppSettings,
        assistant: any NoteAssistant = FoundationModelNoteAssistant(),
        availability: @escaping @Sendable (TranscriptionLanguage) -> LanguageModelAvailability = LanguageModelAvailability.current,
        now: @escaping @Sendable () -> Date = { .now }
    ) {
        answering = NoteQuestionAnswering(knowledge: knowledge, settings: settings, assistant: assistant, availability: availability)
        self.now = now
    }

    public var modelAvailability: LanguageModelAvailability {
        answering.modelAvailability
    }

    public func send(_ question: String) {
        let question = question.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !question.isEmpty, !isResponding else { return }
        let history = completedTurns()
        messages.append(ChatMessage(role: .user, text: question))
        messages.append(ChatMessage(role: .assistant, text: "", isPending: true))
        isResponding = true
        responseTask = Task { [weak self] in
            guard let self else { return }
            let answer = await answering.respond(to: question, history: history, now: now()) { status in
                if let index = self.messages.lastIndex(where: { $0.isPending }) {
                    self.messages[index].status = status
                }
            }
            guard !Task.isCancelled else { return }
            if let index = messages.lastIndex(where: { $0.isPending }) {
                messages[index] = answer
            }
            isResponding = false
            responseTask = nil
        }
    }

    public func cancel() {
        responseTask?.cancel()
        responseTask = nil
        messages.removeAll { $0.isPending }
        isResponding = false
    }

    public func reset() {
        cancel()
        messages.removeAll()
    }

    // MARK: - Answering

    /// Answers one question. Internal for tests.
    func respond(to question: String, history: [ChatTurn]) async -> ChatMessage {
        await answering.respond(to: question, history: history, now: now())
    }

    /// Internal for tests.
    nonisolated static func merge(_ generated: AssistantPlan, into plan: inout QueryPlan, now: Date, calendar: Calendar = .current) {
        NoteQuestionAnswering.merge(generated, into: &plan, now: now, calendar: calendar)
    }

    private func completedTurns() -> [ChatTurn] {
        var turns: [ChatTurn] = []
        var pendingQuestion: String?
        for message in messages where !message.isPending {
            switch message.role {
            case .user:
                pendingQuestion = message.text
            case .assistant:
                if let question = pendingQuestion {
                    turns.append(ChatTurn(question: question, answer: message.text))
                    pendingQuestion = nil
                }
            }
        }
        return Array(turns.suffix(3))
    }
}
